int	my_isalpha(char c)
{
	return ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z'));
}

int	ft_str_is_alpha(char *str)
{
	while (*str != '\0' && my_isalpha(*str))
	{
		str++;
	}
	if (*str != '\0')
	{
		return (0);
	}
	return (1);
}
