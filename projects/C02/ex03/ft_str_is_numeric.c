int	my_isnum(char c)
{
	return (c >= '0' && c <= '9');
}

int	ft_str_is_numeric(char *str)
{
	while (*str != '\0' && my_isnum(*str))
	{
		str++;
	}
	if (*str != '\0')
	{
		return (0);
	}
	return (1);
}
