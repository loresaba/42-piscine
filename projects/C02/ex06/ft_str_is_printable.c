int	my_isprint(char c)
{
	return (c >= 32 && c <= 126);
}

int	ft_str_is_printable(char *str)
{
	while (*str != '\0' && my_isprint(*str))
	{
		str++;
	}
	if (*str != '\0')
	{
		return (0);
	}
	return (1);
}
