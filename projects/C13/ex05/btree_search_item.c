#include "ft_btree.h"

void	*btree_search_item(t_btree *root, void *data_ref,
	int (*cmpf)(void *, void *))
{
	void	*ele;

	if (root == 0 || cmpf == 0)
		return (0);
	ele = btree_search_item(root->left, data_ref, cmpf);
	if (ele != 0)
		return (ele);
	if (cmpf(root->item, data_ref) == 0)
		return (root->item);
	return (btree_search_item(root->right, data_ref, cmpf));
}
